// Version codes for the per-ABI APKs F-Droid builds: versionCode * 10 + the
// ABI's digit, as F-Droid asks. Flutter's own scheme adds 1000, 2000 or 4000
// instead, which puts every arm64 build above every later 32-bit one; with
// the ABI in the last digit, a newer release always has the higher code.
// This runs after Flutter's override, so it is the one that sticks.
val abiCodes = mapOf("armeabi-v7a" to 1, "arm64-v8a" to 2, "x86_64" to 3)
android.applicationVariants.configureEach {
    val variant = this
    variant.outputs.forEach { output ->
        val abiVersionCode = abiCodes[output.filters.find { it.filterType == "ABI" }?.identifier]
        if (abiVersionCode != null) {
            (output as ApkVariantOutputImpl).versionCodeOverride = variant.versionCode * 10 + abiVersionCode
        }
    }
}
